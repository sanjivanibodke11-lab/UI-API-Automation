package koti;

public class switch_add {
    public static void main(String args[]){
        int a=1; int b=2;
        switch(a+b)
        {
            case 1:
                System.out.println("1");
                break;
            case 2:
                System.out.println("2");
case 3:
System.out.println("3");

            default:
                System.out.println("no number");

        }
    }
}

