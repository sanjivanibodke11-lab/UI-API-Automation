package koti;

public class switch_day {
    public static void main(String[] args){
        int n=2;
        switch(n){
            case 0:
                System.out.println("monday");
                break;
            case 1:
                System.out.println("tuesday");
                break;
            case 2:
                System.out.println("wedesday");
                break;
            case 3:
                System.out.println("thursday");
                break;
            default:
                System.out.println("no day");
        }
    }
}

